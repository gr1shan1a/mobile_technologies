function sample(cards, count, random) {
    if (count !== Math.floor(count) || count < 1 || count > cards.length) return [];
    var result = cards.slice(0);
    var rng = random || Math.random;
    for (var i = result.length - 1; i > 0; --i) {
        var j = Math.floor(rng() * (i + 1));
        var item = result[i]; result[i] = result[j]; result[j] = item;
    }
    return result.slice(0, count);
}
